"""Tests for `scripts/report_to_pins.py`.

The script turns a `pip install --dry-run --report` file into the exact pins of
`function_app/requirements.txt`.
"""

import json
import subprocess
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
SCRIPT = REPO_ROOT / "scripts" / "report_to_pins.py"


def entry(name: str, version: str, *, is_direct: bool = False) -> dict[str, Any]:
    return {
        "download_info": {"url": f"https://files.pythonhosted.org/{name}.whl"},
        "is_direct": is_direct,
        "requested": True,
        "metadata": {"name": name, "version": version},
    }


def run(tmp_path: Path, *installs: dict[str, Any]) -> subprocess.CompletedProcess[str]:
    report = tmp_path / "report.json"
    report.write_text(json.dumps({"version": "1", "install": list(installs)}))
    return subprocess.run(
        [sys.executable, str(SCRIPT), str(report)],
        capture_output=True,
        text=True,
        timeout=30,
    )


def test_pins_are_exact_sorted_and_use_canonical_names(tmp_path: Path):
    result = run(
        tmp_path,
        entry("Typing_Extensions", "4.15.0"),
        entry("requests", "2.34.2"),
        entry("azure-functions", "2.3.0"),
    )
    assert result.returncode == 0, result.stderr
    assert result.stdout.startswith(
        "# Generated by scripts/compile-function-requirements.sh"
    )
    pins = [line for line in result.stdout.splitlines() if not line.startswith("#")]
    assert pins == [
        "azure-functions==2.3.0",
        "requests==2.34.2",
        "typing-extensions==4.15.0",
    ]


def test_a_url_requirement_is_refused(tmp_path: Path):
    result = run(tmp_path, entry("requests", "2.34.2", is_direct=True))
    assert result.returncode == 1
    assert "direct URL" in result.stderr
    assert result.stdout == ""


def test_an_empty_report_is_refused(tmp_path: Path):
    result = run(tmp_path)
    assert result.returncode == 1
    assert "nothing to install" in result.stderr
    assert result.stdout == ""
